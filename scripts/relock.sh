#!/usr/bin/env bash
# Regenerate requirements.lock after changing a top-level pin in pyproject.toml.
# Resolves for Python 3.12 / Linux x86_64 wheels without installing anything.
set -euo pipefail
PLAT=()
for v in $(seq 17 39); do PLAT+=(--platform "manylinux_2_${v}_x86_64"); done
PLAT+=(--platform manylinux2014_x86_64 --platform linux_x86_64)
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
PINS=$(python3 - <<'EOF'
import tomllib
d = tomllib.load(open("pyproject.toml", "rb"))["project"]
print(" ".join(d["dependencies"] + d["optional-dependencies"]["train"]))
EOF
)
# shellcheck disable=SC2086
pip install --dry-run --ignore-installed --quiet --report "$TMP/report.json" --python-version 3.12 \
  "${PLAT[@]}" --only-binary=:all: --target "$TMP/t" $PINS
python3 - "$TMP/report.json" <<'EOF'
import json, sys
rows = sorted((i["metadata"]["name"].lower(), i["metadata"]["version"]) for i in json.load(open(sys.argv[1]))["install"])
with open("requirements.lock", "w") as f:
    f.write("# Fully resolved lock for Python 3.12, Linux x86_64, CUDA 13 wheels.\n")
    f.write("# Generated by scripts/relock.sh from the top-level pins in pyproject.toml.\n")
    f.writelines(f"{n}=={v}\n" for n, v in rows)
print(f"locked {len(rows)} packages")
EOF
