#!/usr/bin/env bash
# Regenerate requirements.lock after changing a top-level pin in pyproject.toml.
# Uses uv so environment markers (python_full_version etc.) are evaluated for the TARGET interpreter,
# not the one running this script. (pip --python-version did not, which produced an unsatisfiable lock.)
set -euo pipefail
command -v uv >/dev/null || { echo "uv not found: pip install uv"; exit 1; }
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
python3 - > "$TMP/top.in" <<'PY'
import tomllib
d = tomllib.load(open("pyproject.toml", "rb"))["project"]
print("\n".join(d["dependencies"] + d["optional-dependencies"]["train"]))
PY
uv pip compile "$TMP/top.in" --python-version 3.12 --python-platform x86_64-manylinux_2_28 \
  --no-header --no-annotate -o "$TMP/lock.txt"
# Verify the lock actually installs for the target (dry run, no download of wheels into an env).
uv pip install --dry-run -r "$TMP/lock.txt" --python-version 3.12 --python-platform x86_64-manylinux_2_28 \
  --target "$TMP/t" > /dev/null
{
  echo "# Fully resolved lock for Python 3.12, Linux x86_64 (manylinux_2_28), CUDA 13 wheels."
  echo "# Generated by scripts/relock.sh (uv pip compile) from the top-level pins in pyproject.toml."
  grep -E "==" "$TMP/lock.txt"
} > requirements.lock
echo "locked $(grep -c '==' requirements.lock) packages; install plan verified for Python 3.12"
